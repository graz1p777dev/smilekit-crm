// Тексты Instagram-бота — отдельно от логики, чтобы их можно было прочитать
// из теста и из клиентских компонентов (в bot-reply/dm-bot лежит service-role
// клиент Supabase, импортировать их в браузер нельзя).
//
// Правила те же, что у WhatsApp-бота: никаких медицинских обещаний, скидки
// только две разрешённые ступени (1290, затем 1190 — см. DISCOUNT_OFFER_*
// в src/lib/greenapi/bot-reply.ts), цена пишется через пробел перед «сом».

/** Комментарий про цену — отвечаем цифрой прямо под постом, без «напишите в директ». */
export const COMMENT_PRICE_QUESTION = /цена|цену|стоит|стоимост|почём|почем|сколько|канча|баа|price/i

/** Комментарий про доставку/город. */
export const COMMENT_DELIVERY_QUESTION = /доставк|привез|отправля|курьер|жеткир/i

export const COMMENT_REPLY_PRICE =
  'Одна коробка — 1 490 сом, в ней 14 полосок на полный курс 😊'

export const COMMENT_REPLY_DELIVERY =
  'Доставка есть 😊 Напишите нам в директ — подскажем по вашему городу.'

export const COMMENT_REPLY_DEFAULT =
  'Спасибо за комментарий! 😊 Напишите нам в директ — ответим подробно.'

/**
 * Приватный ответ в директ на комментарий («private reply»). Meta разрешает
 * его ровно один раз на комментарий и только пока комментарий свежий —
 * поэтому текст самодостаточный, без отсылок к предыдущей переписке.
 */
export const COMMENT_PRIVATE_REPLY =
  'Здравствуйте! 😊 Вы написали комментарий под нашим постом — давайте продолжим здесь, так удобнее. ' +
  'Подскажите, что вас интересует?'

/** Ответ ИИ не получен даже со второй попытки — лучше короткий честный текст, чем тишина. */
export const DM_AI_FAILURE_REPLY = 'Извините, не расслышала 😊 Уточните, пожалуйста, ещё раз?'

/** Короткий ответ под комментарий — по теме, без обещаний результата. */
export function commentReplyFor(text: string): string {
  if (COMMENT_PRICE_QUESTION.test(text)) return COMMENT_REPLY_PRICE
  if (COMMENT_DELIVERY_QUESTION.test(text)) return COMMENT_REPLY_DELIVERY
  return COMMENT_REPLY_DEFAULT
}
