-- ============================================================================
-- 063 · Индекс для аналитики: сообщения клиентов по времени
--
-- Почти каждая функция аналитики начинается с «кто писал в период»:
-- sender = 'client' AND created_at в периоде → chat_id. Раньше это шло по
-- idx_chat_messages_created_at с чтением строк таблицы (за 30 дней ~2,4 с
-- на холодную); с этим индексом — только по индексу.
-- Строится CONCURRENTLY: таблицу пишет бот, блокировать запись нельзя.
-- Запускать отдельной командой, не в транзакции.
-- ============================================================================

CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_chat_messages_client_created
  ON public.chat_messages (created_at) INCLUDE (chat_id)
  WHERE sender = 'client';
