-- ============================================================================
-- 065 · Индекс переписки: чат + время
--
-- Горячие запросы вебхука WhatsApp и CRM читают «последние N сообщений
-- чата»: chat_id = $1 ORDER BY created_at [DESC, id DESC] LIMIT N
-- (история для ответа бота в bot-reply.ts, «писал ли менеджер» в
-- chat-control.ts, переписка в карточке сделки, handoff-карточка).
-- Индекса (chat_id, created_at) не было: планировщик шёл по
-- idx_chat_messages_created_at через всю таблицу и отбрасывал чужие чаты —
-- на проде 19.09 ~0,5 с на запрос и 20 тыс. отброшенных строк (EXPLAIN
-- ANALYZE, чат с 1336 сообщениями), и тем дольше, чем старее переписка.
-- С этим индексом — сразу нужные строки чата в нужном порядке.
-- Строится CONCURRENTLY: таблицу пишет бот, блокировать запись нельзя.
-- Запускать отдельной командой, не в транзакции.
-- ============================================================================

CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_chat_messages_chat_created
  ON public.chat_messages (chat_id, created_at, id);
